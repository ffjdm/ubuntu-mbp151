#!/usr/bin/env bash
set -euo pipefail

# Promote the installed, tested candidate into an immutable validated boot slot.
# Never overwrite the historical Intel stable files or an existing validated slot.

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
SOURCE="$ROOT/build/source/intel-gmux.c"
CANDIDATE="$ROOT/build/candidate"
ESP=/boot/efi
ESP_DIR="$ESP/EFI/custom"
GRUB_SCRIPT=/etc/grub.d/42_mbp151_validated
ENTRY_ID=ubuntu-mbp151-intel-validated
LOCK="$ROOT/build/.promote.lock"

fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
info() { printf '%s\n' "$*"; }
sha() { sha256sum "$1" | cut -d' ' -f1; }

[[ $# -eq 0 ]] || fail 'Usage: sudo ./promote.sh'
[[ $(id -u) -eq 0 ]] || fail 'Run this script with sudo'
for tool in gcc ld nm objcopy sha256sum findmnt blkid flock cmp cp mv chmod update-grub grub-set-default grub-editenv python3 mktemp; do
    command -v "$tool" >/dev/null 2>&1 || fail "Missing command: $tool"
done
[[ -s "$SOURCE" ]] || fail 'Missing prepared EFI source; run setup.sh'
[[ -d "$CANDIDATE" && -f "$CANDIDATE/.build-manifest" ]] || fail 'Missing candidate build'
[[ -s "$CANDIDATE/intel-before-candidate.efi" && -s "$CANDIDATE/ubuntu-intel-candidate.efi" ]] || fail 'Missing candidate binaries'
[[ -d "$ESP_DIR" && ! -L "$ESP_DIR" ]] || fail 'Missing ESP custom directory'
[[ -s "$ESP_DIR/intel-before-no-ghost.efi" && -s "$ESP_DIR/ubuntu-intel-no-ghost.efi" ]] || fail 'Historical stable files are missing'
[[ "$(findmnt -n -o FSTYPE --target "$ESP")" == vfat ]] || fail 'ESP must be mounted as vfat'
ESP_UUID=$(blkid -s UUID -o value "$(findmnt -n -o SOURCE --target "$ESP")")
[[ "$ESP_UUID" =~ ^[a-fA-F0-9]{4}-[a-fA-F0-9]{4}$ ]] || fail 'Invalid ESP UUID'

mkdir -p -- "$ROOT/build"
exec 9>"$LOCK"
flock -x 9

read -r input_sha helper_sha uki_sha < "$CANDIDATE/.build-manifest"
[[ "$input_sha" =~ ^[a-f0-9]{64}$ && "$helper_sha" =~ ^[a-f0-9]{64}$ && "$uki_sha" =~ ^[a-f0-9]{64}$ ]] || fail 'Malformed candidate manifest'
[[ "$(sha "$CANDIDATE/intel-before-candidate.efi")" == "$helper_sha" && "$(sha "$CANDIDATE/ubuntu-intel-candidate.efi")" == "$uki_sha" ]] || fail 'Candidate build checksum mismatch'
for name in intel-before-candidate.efi ubuntu-intel-candidate.efi; do
    [[ -f "$ESP_DIR/$name" && ! -L "$ESP_DIR/$name" ]] || fail "Candidate is not installed: $name"
    [[ "$(sha "$ESP_DIR/$name")" == "$(sha "$CANDIDATE/$name")" ]] || fail "Installed candidate differs from build: $name"
done

TMP=$(mktemp -d)
trap 'rm -rf -- "$TMP"' EXIT

# The EFI helper embeds the UKI path. Copying it unchanged would NOT isolate
# the validated slot: it would continue booting the replaceable candidate UKI.
python3 - "$SOURCE" "$TMP/validated.c" <<'PY'
from pathlib import Path
import sys
s = Path(sys.argv[1]).read_text()
for old, new in (
    ('ubuntu-intel-no-ghost.efi', 'ubuntu-intel-validated.efi'),
    ('intel-before-no-ghost.log', 'intel-before-validated.log'),
):
    if s.count(old) < 1:
        sys.exit(f'ERROR: Missing expected EFI source reference: {old}')
    s = s.replace(old, new)
Path(sys.argv[2]).write_text(s)
PY

gcc -I/usr/include/efi -I/usr/include/efi/x86_64 -DGNU_EFI_USE_MS_ABI \
    -fpic -ffreestanding -fno-stack-protector -fno-stack-check -fshort-wchar \
    -mno-red-zone -maccumulate-outgoing-args -Wall -Wextra -Werror -O2 \
    -c "$TMP/validated.c" -o "$TMP/validated.o"
ld -nostdlib -znocombreloc -T /usr/lib/elf_x86_64_efi.lds \
    -shared -Bsymbolic /usr/lib/crt0-efi-x86_64.o \
    "$TMP/validated.o" -L/usr/lib -lefi -lgnuefi -o "$TMP/validated.so"
[[ -z "$(nm -u "$TMP/validated.so")" ]] || fail 'Unresolved EFI symbols'
objcopy -j .text -j .data -j .rodata -j .dynamic -j .dynsym -j .dynstr \
    -j .rel -j .rela -j .reloc -O pei-x86-64 --subsystem=10 \
    "$TMP/validated.so" "$TMP/intel-before-validated.efi"
cp -- "$ESP_DIR/ubuntu-intel-candidate.efi" "$TMP/ubuntu-intel-validated.efi"

cat > "$TMP/grub-entry" <<GRUB
#!/bin/sh
exec tail -n +3 \$0
# Generated by ubuntu-mbp151/promote.sh; validated boot slot.
menuentry 'Ubuntu MBP 15,1 - Intel validated' --id $ENTRY_ID {
    insmod part_gpt
    insmod fat
    search --no-floppy --fs-uuid --set=root $ESP_UUID
    chainloader /EFI/custom/intel-before-validated.efi
}
GRUB
chmod 755 "$TMP/grub-entry"

# Check every destination before writing anything. Never overwrite differences.
for name in intel-before-validated.efi ubuntu-intel-validated.efi; do
    target="$ESP_DIR/$name"
    if [[ -e "$target" || -L "$target" ]]; then
        [[ -f "$target" && ! -L "$target" ]] || fail "Unexpected validated path: $target"
        cmp -s "$TMP/$name" "$target" || fail "Validated slot already exists with different content: $target"
    fi
done
if [[ -e "$GRUB_SCRIPT" || -L "$GRUB_SCRIPT" ]]; then
    [[ -f "$GRUB_SCRIPT" && ! -L "$GRUB_SCRIPT" ]] || fail "Unexpected GRUB script path: $GRUB_SCRIPT"
    cmp -s "$TMP/grub-entry" "$GRUB_SCRIPT" || fail 'Existing validated GRUB entry differs'
fi

# Preserve existing GRUB settings for recovery; only GRUB_DEFAULT is changed.
[[ -f /etc/default/grub && ! -L /etc/default/grub ]] || fail 'Missing or unexpected /etc/default/grub'
python3 - /etc/default/grub "$TMP/grub-default" <<'PY'
from pathlib import Path
import sys
s = Path(sys.argv[1]).read_text()
lines = s.splitlines(keepends=True)
indices = [i for i, line in enumerate(lines) if line.startswith('GRUB_DEFAULT=')]
if len(indices) != 1:
    sys.exit('ERROR: Expected exactly one GRUB_DEFAULT setting')
lines[indices[0]] = 'GRUB_DEFAULT=saved\n'
Path(sys.argv[2]).write_text(''.join(lines))
PY

for name in intel-before-validated.efi ubuntu-intel-validated.efi; do
    if [[ ! -e "$ESP_DIR/$name" ]]; then
        cp -- "$TMP/$name" "$ESP_DIR/$name"
        [[ "$(sha "$ESP_DIR/$name")" == "$(sha "$TMP/$name")" ]] || fail "ESP verification failed: $name"
        info "Installed: $ESP_DIR/$name"
    fi
done
if [[ ! -e "$GRUB_SCRIPT" ]]; then
    cp -- "$TMP/grub-entry" "$GRUB_SCRIPT"
    chmod 755 "$GRUB_SCRIPT"
    info "Installed GRUB entry: $GRUB_SCRIPT"
fi

if ! cmp -s "$TMP/grub-default" /etc/default/grub; then
    cp -- /etc/default/grub /etc/default/grub.mbp151-before-validated.bak
    cp -- "$TMP/grub-default" /etc/default/grub
    info 'Configured GRUB_DEFAULT=saved'
fi

update-grub || fail 'update-grub failed; inspect GRUB before rebooting'
grub-set-default "$ENTRY_ID"
[[ "$(grub-editenv - list)" == *"saved_entry=$ENTRY_ID"* ]] || fail 'Unable to verify saved GRUB entry'
info "Default boot entry: $ENTRY_ID"
info 'Historical stable and AMD fallback entries remain untouched.'
info 'Validated EFI files will not be overwritten by future candidate builds.'
