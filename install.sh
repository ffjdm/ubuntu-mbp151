#!/usr/bin/env bash
set -euo pipefail

# Install a verified EFI candidate and an independent GRUB test entry.
# Never change the default boot entry or overwrite the known-good Intel loader.

# -----------------------------------------------------------------------------
# Paths and configuration
# -----------------------------------------------------------------------------

ROOT=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)
CANDIDATE="$ROOT/build/candidate"
ESP="/boot/efi"
ESP_DIR="$ESP/EFI/custom"
HELPER="intel-before-candidate.efi"
UKI="ubuntu-intel-candidate.efi"
GRUB_SCRIPT="/etc/grub.d/41_mbp151_candidate"
LOCK="$ROOT/build/.install.lock"

info() { printf '%s\n' "$*"; }
fail() { printf 'ERROR: %s\n' "$*" >&2; exit 1; }
sha() { sha256sum "$1" | cut -d' ' -f1; }

# -----------------------------------------------------------------------------
# Prerequisites and candidate integrity
# -----------------------------------------------------------------------------

[[ $# -eq 0 ]] || fail "Usage: sudo ./install.sh"
[[ $(id -u) -eq 0 ]] || fail "Run this script with sudo"
for cmd in sha256sum findmnt blkid flock cmp mktemp cp mv chmod sync update-grub python3; do
    command -v "$cmd" >/dev/null 2>&1 || fail "Missing command: $cmd"
done
[[ -d "$CANDIDATE" && ! -L "$CANDIDATE" ]] || fail "Missing candidate directory; run build.sh first"
[[ -s "$CANDIDATE/$HELPER" && -s "$CANDIDATE/$UKI" && -s "$CANDIDATE/.build-manifest" ]] || fail "Candidate files or manifest are missing"
read -r input_sha helper_sha uki_sha < "$CANDIDATE/.build-manifest"
[[ "$input_sha" =~ ^[a-f0-9]{64}$ && "$helper_sha" =~ ^[a-f0-9]{64}$ && "$uki_sha" =~ ^[a-f0-9]{64}$ ]] || fail "Malformed build manifest"
[[ "$(sha "$CANDIDATE/$HELPER")" == "$helper_sha" ]] || fail "Candidate helper checksum mismatch"
[[ "$(sha "$CANDIDATE/$UKI")" == "$uki_sha" ]] || fail "Candidate UKI checksum mismatch"

[[ -d "$ESP_DIR" && ! -L "$ESP_DIR" ]] || fail "Expected existing EFI directory is missing: $ESP_DIR"
[[ -s "$ESP_DIR/intel-before-no-ghost.efi" && -s "$ESP_DIR/ubuntu-intel-no-ghost.efi" ]] || fail "Stable Intel boot files are missing; refusing installation"
[[ "$(findmnt -n -o FSTYPE --target "$ESP")" == "vfat" ]] || fail "ESP is not mounted as vfat at $ESP"
ESP_UUID=$(blkid -s UUID -o value "$(findmnt -n -o SOURCE --target "$ESP")")
[[ "$ESP_UUID" =~ ^[A-Fa-f0-9]{4}-[A-Fa-f0-9]{4}$ ]] || fail "Cannot determine ESP filesystem UUID"

mkdir -p -- "$ROOT/build"
exec 9>"$LOCK"
flock -x 9 || fail "Unable to acquire install lock"

# -----------------------------------------------------------------------------
# Protect existing installation and generate the GRUB test entry
# -----------------------------------------------------------------------------

for name in "$HELPER" "$UKI"; do
    target="$ESP_DIR/$name"
    if [[ -e "$target" || -L "$target" ]]; then
        [[ -f "$target" && ! -L "$target" ]] || fail "Unexpected existing ESP path: $target"
        [[ "$(sha "$target")" == "$(sha "$CANDIDATE/$name")" ]] || fail "Existing ESP candidate differs: $target. Refusing to overwrite."
    fi
done

TMP=$(mktemp -d)
cleanup() { rm -rf -- "$TMP"; }
trap cleanup EXIT

cat > "$TMP/grub-entry" <<GRUB
#!/bin/sh
exec tail -n +3 \$0
# Generated by ubuntu-mbp151/install.sh. Test entry only; not the default.
menuentry 'Ubuntu MBP 15,1 - Intel candidate (test)' --id ubuntu-mbp151-intel-candidate {
    insmod part_gpt
    insmod fat
    search --no-floppy --fs-uuid --set=root $ESP_UUID
    chainloader /EFI/custom/$HELPER
}
GRUB
chmod 755 "$TMP/grub-entry"

if [[ -e "$GRUB_SCRIPT" || -L "$GRUB_SCRIPT" ]]; then
    [[ -f "$GRUB_SCRIPT" && ! -L "$GRUB_SCRIPT" ]] || fail "Unexpected existing GRUB script path: $GRUB_SCRIPT"
    cmp -s "$TMP/grub-entry" "$GRUB_SCRIPT" || fail "Existing GRUB test entry differs: $GRUB_SCRIPT. Refusing to overwrite."
fi

# -----------------------------------------------------------------------------
# Install only missing files, then regenerate the GRUB menu
# -----------------------------------------------------------------------------

changed=0
for name in "$HELPER" "$UKI"; do
    target="$ESP_DIR/$name"
    if [[ ! -e "$target" ]]; then
        cp -- "$CANDIDATE/$name" "$TMP/$name"
        [[ "$(sha "$TMP/$name")" == "$(sha "$CANDIDATE/$name")" ]] || fail "Staging checksum mismatch: $name"
        cp -- "$TMP/$name" "$target"
        [[ "$(sha "$target")" == "$(sha "$CANDIDATE/$name")" ]] || fail "ESP checksum mismatch after copy: $name"
        info "Installed: $target"
        changed=1
    else
        info "Already installed: $target"
    fi
done

if [[ ! -e "$GRUB_SCRIPT" ]]; then
    cp -- "$TMP/grub-entry" "$GRUB_SCRIPT"
    chmod 755 "$GRUB_SCRIPT"
    info "Installed GRUB test entry: $GRUB_SCRIPT"
    changed=1
fi

if (( changed )); then
    sync
    update-grub || fail "GRUB update failed; installed files were not removed. Inspect GRUB before rebooting"
    info "Candidate installed. Select 'Ubuntu MBP 15,1 - Intel candidate (test)' manually in GRUB."
else
    info "Candidate installation is already up to date; no changes made."
fi
info "Stable Intel and AMD fallback entries were not changed by this script."
info "The default GRUB selection was not changed."
